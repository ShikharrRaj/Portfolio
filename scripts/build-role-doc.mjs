#!/usr/bin/env node
// build-role-doc.mjs — reconciles the CEO's "one readable 800–1500 line doc per role" instinct
// with tiered machine loading. Concatenates a role's always-loaded body + all its on-demand
// _role-assets into ONE human-readable doc under docs/roles/<slug>.md. Depth for people;
// tiered loading for the machine.
// Run:  node scripts/build-role-doc.mjs <role-slug>          (or no arg = all authored roles)
import { readFileSync, writeFileSync, readdirSync, statSync, existsSync, mkdirSync } from 'node:fs';
import { join, extname, basename, relative } from 'node:path';

const ROOT = process.cwd();

function findRoleFile(slug) {
  for (const p of [`.claude/agents/${slug}.md`, `.claude/agents/specialists/${slug}.md`]) {
    if (existsSync(join(ROOT, p))) return p;
  }
  return null;
}

function walkFiles(dir) {
  const abs = join(ROOT, dir);
  if (!existsSync(abs)) return [];
  const out = [];
  for (const name of readdirSync(abs).sort()) {
    const rel = join(dir, name);
    if (statSync(join(ROOT, rel)).isDirectory()) out.push(...walkFiles(rel));
    else out.push(rel);
  }
  return out;
}

function build(slug) {
  const roleFile = findRoleFile(slug);
  if (!roleFile) { console.error(`✗ no role file for "${slug}"`); return false; }
  const parts = [];
  parts.push(`<!-- GENERATED by scripts/build-role-doc.mjs — do not edit. Source of truth: ${roleFile} + _role-assets/${slug}/ -->`);
  parts.push(`# Role Dossier — ${slug}\n`);
  parts.push(`## ═══ ALWAYS-LOADED CORE (${roleFile}) ═══\n`);
  parts.push(readFileSync(join(ROOT, roleFile), 'utf8').trim());
  const assets = walkFiles(`.claude/agents/_role-assets/${slug}`);
  for (const a of assets) {
    if (extname(a) && extname(a) !== '.md') continue;
    parts.push(`\n\n## ═══ ON-DEMAND · ${relative(`.claude/agents/_role-assets/${slug}`, a)} ═══\n`);
    parts.push(readFileSync(join(ROOT, a), 'utf8').trim());
  }
  const outDir = join(ROOT, 'docs/roles');
  mkdirSync(outDir, { recursive: true });
  const outPath = join('docs/roles', `${slug}.md`);
  writeFileSync(join(ROOT, outPath), parts.join('\n') + '\n');
  const lineCount = parts.join('\n').split('\n').length;
  console.log(`✓ ${outPath} (${lineCount} lines, ${assets.length} asset file(s) merged)`);
  return true;
}

const arg = process.argv[2];
let slugs;
if (arg) {
  slugs = [arg];
} else {
  slugs = walkFiles('.claude/agents')
    .filter((p) => extname(p) === '.md' && !p.includes('_role-assets'))
    .map((p) => basename(p, '.md'));
}
let ok = true;
for (const s of slugs) ok = build(s) && ok;
process.exit(ok ? 0 : 1);
